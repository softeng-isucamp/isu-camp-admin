-- A controlled vocabulary for what a Building is, alongside public.location_type.
--
-- public.building.classification holds free text and, in practice, only ever
-- two values: 'Building' on 53 rows and 'Facility' on 4. That says almost
-- nothing about a place - a canteen, a car park and a college are all
-- "Building" - so the directory gains a type the way indoor Locations already
-- have one.
--
-- classification is deliberately left in place and untouched. It still drives
-- the "type" field of every Building DTO, the Dashboard's analytics keys and
-- the map's object kinds, and the new column starts empty on every row: a
-- Building has no type until somebody assigns one. Nothing is migrated
-- automatically, because 'Building' carries no information to migrate.
-- Dropping classification is a later change, once every row has been edited.
--
-- Shaped exactly like public.location_type: identity primary key, unique
-- name, optional description.

BEGIN;

CREATE TABLE IF NOT EXISTS public.building_type (
    type_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name   varchar NOT NULL UNIQUE,
    description text
);

-- Seeded by name, so re-running adds nothing and never renumbers a type that
-- a Building already points at.
INSERT INTO public.building_type (type_name, description) VALUES
    ('College',          'An academic college or school, and its classrooms and faculty offices.'),
    ('Campus Services',  'Administrative and support offices serving the whole campus.'),
    ('Food',             'Canteens, cafeterias and food courts.'),
    ('Parking',          'Vehicle parking areas.'),
    ('Facility',         'Shared grounds and amenities: gyms, ovals, study areas, comfort rooms.')
ON CONFLICT (type_name) DO NOTHING;

-- Nullable on purpose. Every existing Building starts without a type, and the
-- portal is where each one is given the right one; a default would quietly
-- label 57 buildings with a guess.
ALTER TABLE public.building
    ADD COLUMN IF NOT EXISTS type_id bigint;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_building_building_type'
    ) THEN
        ALTER TABLE public.building
            ADD CONSTRAINT fk_building_building_type
            FOREIGN KEY (type_id) REFERENCES public.building_type (type_id);
    END IF;
END $$;

-- Buildings are listed and filtered by type, and the column is mostly NULL
-- while the directory is being edited, so the index covers only the rows that
-- have been assigned one.
CREATE INDEX IF NOT EXISTS building_type_id_idx
    ON public.building (type_id) WHERE type_id IS NOT NULL;

COMMIT;

